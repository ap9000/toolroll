import { afterEach, expect, test } from 'vitest';
import { mkdtempSync, writeFileSync, rmSync, realpathSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { openStore, type Store } from './store.js';
import { runProjectCommand, projectProfilePath } from './project-cli.js';
import { mintCoordinator } from './coordinator.js';
import { projectOutcomes } from './project-outcomes.js';
let store: Store, dir: string;
afterEach(() => { store?.close(); if (dir) rmSync(dir, { recursive: true, force: true }); });
test('CLI returns the shared report and refuses a missing or foreign saved credential instead of falling back to local access', async () => {
  dir = realpathSync(mkdtempSync(join(tmpdir(), 'activity-cli-')));
  const databaseFile = join(dir, 'test.db'), registryFile = join(dir, 'repos.json'), tokenFile = join(dir, 'token');
  const now = new Date(); store = openStore(databaseFile);
  writeFileSync(registryFile, JSON.stringify({ version: 2, repos: [dir], roots: [] }));
  writeFileSync(projectProfilePath(databaseFile), JSON.stringify({ version: 1, repo: dir, tokenFile: null }));
  const lines: string[] = [];
  const context = { store, databaseFile, registryFile, now, json: true, write: (line: string) => lines.push(line) };
  expect(await runProjectCommand(['activity'], new Map(), context)).toBe(0);
  expect(JSON.parse(lines.at(-1)!).result).toEqual(projectOutcomes(store, dir, now, { principal: 'operator', repos: [dir] }));
  writeFileSync(projectProfilePath(databaseFile), JSON.stringify({ version: 1, repo: dir, tokenFile }));
  expect(await runProjectCommand(['activity'], new Map(), context)).toBe(3);
  expect(JSON.parse(lines.at(-1)!).reason).toBe('unauthenticated');
  const other = mintCoordinator(store, { name: 'foreign', repos: ['/projects/other'], by: 'fixture', now });
  if (!other.ok) throw new Error(other.reason);
  writeFileSync(tokenFile, other.token);
  expect(await runProjectCommand(['activity'], new Map(), context)).toBe(3);
  expect(JSON.parse(lines.at(-1)!).reason).toBe('not-found');
});
