/** What a `sign-ins` check reads and writes beyond its fence (check-access.ts): its exact sign-in files, its own Claude
 * transcript folder (macOS) and Codex's session and log folders. */
export type SignInGrants = { read: string[]; transcripts: string[]; writes: string[];
  /** macOS services the sign-ins need: certificate checking (trustd), without which gh (Go) can't verify GitHub's TLS
   * and calls its own token invalid. Measured with gh 2.x on macOS 26. */
  mach: string[] };

/** The sign-in files a `sign-ins` check reads, by fixed name under the person's home (never from the environment, so no
 * caller's CLAUDE_CONFIG_DIR or GH_CONFIG_DIR points a grant at .ssh): Claude's account and settings (and, on Linux,
 * its credentials file; on a Mac they are in the keychain), gh's hosts and config, and Codex's config and sign-in. */
const SIGN_IN_FILES = (platform: NodeJS.Platform): string[] => [
  ".claude.json", join(".claude", "settings.json"), ...(platform === "linux" ? [join(".claude", ".credentials.json")] : []),
  join(".config", "gh", "hosts.yml"), join(".config", "gh", "config.yml"), join(".codex", "config.toml"), join(".codex", "auth.json"),
];

/**
 * A `sign-ins` check's grants (sandbox parity C10, srt-style): each sign-in file by its name, read by the check itself
 * through its sandbox. Nothing privileged reads or copies one: the sandbox resolves the name in its own view, so a link
 * planted there into Toolroll's state leads to a denied path (Seatbelt checks the resolved file; bubblewrap resolves
 * inside its mount namespace, where the state is masked). On a Mac, the checkout's own Claude transcript folder (made
 * when absent, only as the real folder it is), whose session files alone are written; and Codex's session and log
 * folders (when ~/.codex is there), never its config.
 */
export function signInGrants(home: string, checkout: string, platform: NodeJS.Platform = process.platform): SignInGrants {
  const base = real(home);
  // Read by name, but only a name that is itself now: every folder from the home folder down a real one, the file a
  // regular file with one name (never a link, never a hard link to something else). The sandbox resolves it again.
  const read = SIGN_IN_FILES(platform).map(name => join(base, name)).filter(path => signInIsItself(base, path));
  const transcript = claudeProjectFolder(base, real(checkout));
  // A transcript folder Claude would name by prefix (a very long checkout path) isn't granted: never a prefix of others.
  const folder = transcript.byPrefix || !existsSync(join(base, ".claude")) ? null : grantFolder(transcript.path);
  const codex = join(base, ".codex");
  const writes = grantFolder(codex, false) === null ? [] : ["sessions", "log"].map(name => grantFolder(join(codex, name))).filter((path): path is string => path !== null);
  return { read, transcripts: folder === null || platform !== "darwin" ? [] : [folder], writes, mach: platform === "darwin" ? ["com.apple.trustd.agent"] : [] };
}

/** Whether a sign-in file is itself, now: every folder from the (real) home folder down a real folder, the file a
 * regular file with one name (never a link, never a hard link to something else). Checked when granted and again right
 * before the launch (invoke.ts); the sandbox resolves the name a third time. */
export function signInIsItself(base: string, path: string): boolean {
  let at = base;
  const parts = relative(base, path).split(sep);
  if (parts.length === 0 || parts[0] === ".." || isAbsolute(relative(base, path))) return false;
  for (const [index, part] of parts.entries()) {
    at = join(at, part);
    try {
      const held = lstatSync(at);
      if (held.isSymbolicLink() || (index < parts.length - 1 ? !held.isDirectory() : !(held.isFile() && held.nlink === 1))) return false;
    } catch { return false; }
  }
  return true;
}

/**
 * Which fence policy a launch runs under (docs/plans/sandbox-parity.md §1.5). v1: the fence as approvals sealed before
 * 0.9.70 knew it (the home configuration, the repositories beside the project and its primary checkout denied to read).
 * v2: those reads open, as in Anthropic's sandbox runtime, less what the project's sealed `readDeny` names. A widening,
 * so only a scope sealed at v2 runs under it; every narrowing applies to both.
 */
export type FencePolicy = 1 | 2;
export const FENCE_POLICY_CURRENT: FencePolicy = 2;

/** Who a launch is (docs/plans/sandbox-parity.md §3): a build's agent, its setup and check commands, a saved result's
 * checks, a flow's setup, script or trigger, or a tool server. Each gets its fence from `fenceFor`, and only from it. */
export type FenceKind = "build" | "command" | "check" | "flow" | "tool-server";

/**
 * What `fenceFor` needs. The boundary and the trusted binding are required, as values or an explicit null (a launch
 * with no checkout), so no caller forgets one; every path comes from Toolroll's own records, never from the checkout.
 */
export type FenceContext = {
  databaseFile: string | null;
  worktree: string | null;
  boundary: TaskBoundary | null;
  binding: WorktreeBinding | null;
  runFolders: RunFolders;
  /** The checkout pools, from the plane's records (CheckoutPool). */
  poolRoots: readonly (string | null)[];
  home?: string;
  /** Denied beside the fence (a provider's live session keys, say). */
  extra?: readonly string[];
  /** The shared dependencies this checkout links, as the plane recorded them. */
  linked?: { repo: string; setupDigest: string | null } | null;
  /** A workspace launch's write allowlist and what it adds read-only (writeAllowlist); absent: writes anywhere its
   * fence allows. */
  writes?: { writes: WriteAllowlist; readOnly: string[] } | null;
  /** The launch's network, when it has one of its own (a flow's: decided by its caller, never left unsaid). */
  network?: NetworkFence;
  /** What it may not read beside the fence, as absolute paths (project-sandbox.ts readDenyPath): denied whole. */
  readDeny?: readonly string[];
  /** macOS services it may also reach (project-sandbox.ts). */
  machLookup?: readonly string[];
  /** The fence policy it runs under: v2 reads other tasks' checkouts (never writes them). */
  policy?: FencePolicy;
  /** The agent the launch runs, whose own sign-in files stay its to write (PROVIDER_HOME). */
  provider?: string;
  /** Scratch folders (a flow's) that stay denied whole inside the pool, whatever the policy. */
  scratchRoots?: readonly string[];
};

/** A launch's sealed sandbox terms (builder.ts launchSandboxOf): its policy version, read denies and mach services. A
 * launch with none sealed is v1 with none of them. */
export type LaunchSandbox = { policy: FencePolicy; readDeny: readonly string[]; machLookup: readonly string[] };
export const LEGACY_SANDBOX: LaunchSandbox = { policy: 1, readDeny: [], machLookup: [] };

/** A build's sandbox terms, exactly as its approval sealed them: an approval from before 0.9.70 is policy v1 (the home
 * configuration denied) with nothing listed. */
export function launchSandboxOf(profile: ExecutionProfile): LaunchSandbox {
  return { policy: profile.fencePolicy ?? 1, readDeny: profile.readDeny ?? [], machLookup: profile.machLookup ?? [] };
}

/** A launch's whole fence: its denied paths, what it gives back, and that it runs inside the OS fence or not at all.
 * Spread into RunOptions as is. */
export type LaunchFence = { kind: FenceKind; fence: string[]; fenceGrants: FenceGrants; confinement: "required" };

/** The one place a launch's fence is made (docs/plans/sandbox-parity.md C1): its denies, its grants, and
 * `confinement: "required"`, so the spawn road refuses it where no OS fence applies rather than running it bare. */
export function fenceFor(kind: FenceKind, ctx: FenceContext): LaunchFence {
  const home = ctx.home === undefined ? {} : { home: ctx.home };
  // The project's read denies join the fence by name, there or not (the runtime denies a path that isn't there yet).
  const fence = agentFence({ databaseFile: ctx.databaseFile, worktree: ctx.worktree, ...home, boundary: ctx.boundary, binding: ctx.binding, runFolders: ctx.runFolders, extra: [...ctx.extra ?? [], ...ctx.readDeny ?? []] });
  const found = fenceGrants({ databaseFile: ctx.databaseFile, worktree: ctx.worktree, boundary: ctx.boundary, runFolders: ctx.runFolders, linked: ctx.linked ?? null, binding: ctx.binding, ...home, poolRoots: ctx.poolRoots });
  // Toolroll's own install, the sandbox runtime's package and the Node running them, never written by anything it
  // launches: rewriting the code that fences a build would switch the fence off.
  const made = { ...found, readOnly: [...new Set([...found.readOnly, ...toolrollInstall(ctx.worktree, ctx.home ?? homedir(), ctx.binding?.main ?? null)])].sort() };
  const written = ctx.writes ?? null;
  const grants: FenceGrants = {
    ...made,
    ...(written === null ? {} : { writes: written.writes, readOnly: [...new Set([...made.readOnly, ...written.readOnly])].sort() }),
    ...(ctx.network === undefined ? {} : { network: ctx.network }),
    ...(ctx.machLookup === undefined || ctx.machLookup.length === 0 ? {} : { machLookup: [...ctx.machLookup] }),
    // Under a write allowlist these are out of reach already; where the launch writes anywhere, they are denied by name.
    writeDenies: homeWriteDenies(ctx.home ?? homedir(), ctx.binding, ctx.provider ?? null),
    ...(made.pool === undefined ? {} : { pool: { ...made.pool, ...(ctx.policy === 2 ? { readable: true as const } : {}),
      // Flows' scratch folders in the pool (and any the caller names) stay denied whole, at every policy version.
      sealed: sealedScratch(ctx.poolRoots, ctx.scratchRoots ?? []) } }),
  };
  return { kind, fence, fenceGrants: grants, confinement: "required" };
}


/** The flows' scratch folders inside the checkout pools (`flow-checks` beside the checkouts) and any a caller names,
 * each denied by name whether or not it is there yet, and where it is a link, where it leads too. */
export function sealedScratch(poolRoots: readonly (string | null)[], named: readonly string[]): string[] {
  const out = new Set<string>();
  for (const path of [...poolRoots.filter((root): root is string => root !== null).map(root => join(real(root), "flow-checks")), ...named.map(one => join(real(dirname(one)), basename(one)))]) {
    out.add(path);
    try { if (lstatSync(path).isSymbolicLink()) out.add(realpathSync(path)); } catch { /* not there, or dangling: denied by name */ }
  }
  return [...out].sort();
}


/**
 * Toolroll's own install as no launch may write it: this package's folder (its compiled code, the sandbox launch
 * helper among it), the sandbox runtime's package wherever it was installed, and the Node running them with the
 * folder it lives in (its npm and global packages beside it), as the real folders they are. Never a folder that holds
 * the launch's own checkout or its repository (a build of Toolroll's own source, run from it: that repository's other
 * files are the primary checkout's, write-denied already), the home folder or one above it, and nothing the user
 * doesn't own (root's folders are out of a build's reach already).
 */
export function toolrollInstall(worktree: string | null, home: string, repository: string | null = null): string[] {
  const own = worktree === null ? null : real(worktree);
  const repo = repository === null ? null : real(repository);
  const uid = process.getuid?.();
  const ours = (path: string) => { try { return uid === undefined || statSync(path).uid === uid; } catch { return false; } };
  let runtime: string[] = [];
  try { runtime = [dirname(dirname(createRequire(import.meta.url).resolve("@anthropic-ai/sandbox-runtime")))]; } catch { runtime = []; }
  const candidates = [resolve(dirname(fileURLToPath(import.meta.url)), ".."), ...runtime, dirname(dirname(real(process.execPath))), real(process.execPath)].map(real);
  const homeReal = real(home);
  return [...new Set(candidates)].filter(path => path !== dirname(path) && path !== homeReal && !inside(homeReal, path)
    && !(own !== null && (own === path || inside(own, path))) && !(repo !== null && (repo === path || inside(repo, path))) && ours(path)).sort();
}

/** Names that run code or reconfigure tools for whoever opens the project next: the sandbox runtime's DANGEROUS_FILES
 * (@anthropic-ai/sandbox-runtime sandbox-utils), and the names its mandatory denies can't hold when they are made
 * after a launch starts (`.envrc`, package-manager and Claude settings). */
export const PROTECTED_FILES: readonly string[] = [".gitconfig", ".gitmodules", ".bashrc", ".bash_profile", ".zshrc", ".zprofile", ".profile", ".ripgreprc", ".mcp.json",
  ".envrc", ".npmrc", ".yarnrc", ".yarnrc.yml", ".claude/settings.json", ".claude/settings.local.json", ".git/config"];
/** Folders protected whole, wherever they are (the runtime's dangerous directories, with Git's hooks). */
export const PROTECTED_DIRS: readonly string[] = [".vscode", ".idea", ".claude/commands", ".claude/agents", ".git/hooks"];

/**
 * The handoff's backstop (builder.ts commit): the changed paths (relative, from Git) that are protected names at any
 * depth, in any case. The sandbox runtime denies these when a launch starts; one made after it started (a new nested
 * folder's `.envrc`, say) gets through the sandbox, and a result that holds it is refused.
 */
export function protectedChanges(changed: readonly string[]): string[] {
  const files = PROTECTED_FILES.map(one => one.toLowerCase());
  return changed.filter(path => {
    const lower = `/${path.toLowerCase()}`;
    // A protected folder's own name too (a link committed as `pkg/.vscode`), not only what is in it.
    return files.some(name => lower.endsWith(`/${name}`)) || PROTECTED_DIRS.some(dir => lower.includes(`/${dir.toLowerCase()}/`) || lower.endsWith(`/${dir.toLowerCase()}`));
  });
}

/**
 * The handoff's backstop for links (builder.ts commit): a staged symbolic link (Git mode 120000) whose path is a
 * protected name or a folder on the way to one (`pkg/.claude`, `.vscode`, `lib/.git`), at any depth, in any case. A
 * link there would lead whoever opens the project to settings, hooks or commands kept anywhere.
 */
export function protectedLinks(links: readonly string[]): string[] {
  const entries = [...PROTECTED_FILES, ...PROTECTED_DIRS].map(one => one.toLowerCase().split("/"));
  return links.filter(path => {
    const parts = path.toLowerCase().split("/").filter(one => one !== "");
    return entries.some(entry => {
      // The link's last parts are the entry's first ones (the whole entry, or a folder on the way to it).
      for (let take = 1; take <= Math.min(entry.length, parts.length); take++) {
        if (parts.slice(parts.length - take).join("/") === entry.slice(0, take).join("/")) return true;
      }
      return false;
    });
  });
}

/** The home folder's own persistence points beyond the protected names (login items, systemd user units and autostart,
 * Git's, gh's, pip's and fish's configuration, the shells' other startup files, SSH and GnuPG, and the folders on a
 * login PATH). Under `.config/` each also stands under $XDG_CONFIG_HOME. */
export const HOME_PERSISTENCE: readonly string[] = ["Library/LaunchAgents", ".config/systemd/user", ".config/autostart", ".config/git", ".config/gh", ".config/pip",
  ".config/fish", ".pip", ".zshenv", ".zlogin", ".bash_login", ".ssh", ".gnupg", ".local/bin", "bin"];
/** The sign-in folders and files at home no launch writes, but an agent its own exact sign-in files (OWN_SIGN_INS). */
const HOME_SIGN_INS: readonly string[] = [".codex", ".claude.json", ".claude/.credentials.json"];
/** The exact sign-in files an agent's own launch still writes (Claude's account and credentials). Codex's harness
 * refreshes its sign-in outside the sandbox, so its commands write none. Configuration and persistence names stay
 * denied for every agent. */
const OWN_SIGN_INS: Readonly<Record<string, readonly string[]>> = { claude: [".claude.json", ".claude/.credentials.json"] };

/** `path` as it resolves now: through every link above it (and at it), however much of it exists. */
function resolvedPath(path: string): string {
  let head = path;
  const rest: string[] = [];
  while (head !== dirname(head)) {
    try { return join(realpathSync(head), ...rest.reverse()); } catch { rest.push(basename(head)); head = dirname(head); }
  }
  return path;
}

/**
 * What no launch writes, whatever its writes, as static write denies for the sandbox runtime (whose own protected names
 * are anchored at the launch's folder only) and Codex's profile: the home folder's protected names (shell profiles, Git
 * and tool configuration), its persistence points and sign-ins (but the launch's own agent's exact sign-in files), and
 * the bound repository's own Git config, hooks and submodules (a linked worktree reaches them through its `.git`
 * file). Each by its name and by where it leads now (a linked ~/.config or LaunchAgents is denied at both ends). On
 * Linux only those there at launch: the runtime holds an absent name with a stand-in nothing can read for the launch's
 * length, and the person's own git and shells then fail on their ~/.gitconfig and ~/.bashrc (measured). Under a write
 * allowlist an absent one is out of reach anyway; under `anywhere` it can be made (an accepted limit).
 */
export function homeWriteDenies(home: string, binding: WorktreeBinding | null, provider: string | null, platform: NodeJS.Platform = process.platform,
  env: Readonly<Record<string, string | undefined>> = process.env): string[] {
  const base = real(home);
  const own = new Set(OWN_SIGN_INS[provider ?? ""] ?? []);
  const names = [...new Set([...PROTECTED_FILES.filter(name => !name.startsWith(".git/")), ...PROTECTED_DIRS.filter(name => !name.startsWith(".git/")), ...HOME_PERSISTENCE, ...HOME_SIGN_INS])]
    .filter(name => !own.has(name));
  const xdg = env["XDG_CONFIG_HOME"];
  const roots = (name: string): string[] => [join(base, name), ...(name.startsWith(".config/") && xdg !== undefined && isAbsolute(xdg) ? [join(xdg, name.slice(".config/".length))] : [])];
  const paths = names.flatMap(name => roots(name).filter(path => platform !== "linux" || existsSync(path)));
  const git = binding === null ? [] : ["config", "hooks", "modules"].map(name => join(real(join(binding.main, ".git")), name));
  return [...new Set([...paths, ...git].flatMap(path => [path, resolvedPath(path)]))].sort();
}

/** A tool server's grants from its build's: never the agent's network or write allowlist (a server keeps its own state
 * where it always has), and never the build's own checkout or launch folder read back (nothing a build wrote loads in a
 * process that holds a tool's secrets). */
export function serverGrantsOf(grants: FenceGrants): FenceGrants {
  const { network: _agentOnly, writes: _agentWrites, ...rest } = grants;
  return {
    ...rest,
    ...(rest.pool === undefined ? {} : { pool: { ...rest.pool, own: null } }),
    ...(rest.runFolders === undefined ? {} : { runFolders: { ...rest.runFolders, own: null } }),
  };
}
