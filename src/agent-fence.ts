/**
 * The runtime's config for a launch (sandbox-runtime.ts SrtTerms), from its fence: every fenced path denied to read and
 * write (with the exact paths read again inside them), the pools' other checkouts write-denied (and, under v1, read-
 * denied) around the build's own, the flows' scratch folders sealed, the launch's writes (its allowlist, or anywhere
 * outside the denies), its mach services and its network.
 */
export function srtTermsOf(fence: readonly string[], grants: FenceGrants = NO_GRANTS): SrtTerms {
  const denyRead = new Set<string>(fence.map(real));
  // A readable grant's own folder is read too: bundlers (esbuild) find node_modules by listing it. The runtime can't
  // grant a listing without the folder's files, so the shared copy's folder is read whole (its ready note among them).
  const allowRead = new Set<string>(grants.readable.flatMap(path => [real(path), real(dirname(path))]));
  const denyWrite = new Set<string>([...fence, ...grants.readOnly].map(real));
  for (const path of grants.writeDenies ?? []) denyWrite.add(path);
  for (const name of grants.homeNames ?? []) { denyRead.add(name); denyWrite.add(name); }
  for (const file of grants.signIns?.read ?? []) allowRead.add(file);
  // Every other launch's private folder unread by pattern (one made after this launch too), this launch's own read
  // again. Writes are denied to those there at launch, under every root: the runtime can't write back inside a write
  // deny, so a pattern would take this launch's own folder too (one made after launch is writable under `anywhere`).
  const folders = grants.runFolders;
  if (folders !== undefined) {
    for (const root of runRoots(folders)) {
      for (const prefix of RUN_FOLDER_PREFIXES) denyRead.add(join(root, `${prefix}*`));
      // And by name, each there right before the launch (this runs at the spawn): on Linux the runtime gives a pattern
      // no mask where a path it allows lies beside its matches. Written: only where the launch writes anywhere (under a
      // write allowlist they are out of its writes already).
      for (const path of otherRunFolders({ root, own: folders.own })) {
        denyRead.add(path);
        if (grants.writes === undefined) denyWrite.add(path);
      }
    }
    if (folders.own !== null) allowRead.add(folders.own);
  }
  const pool = grants.pool;
  if (pool !== undefined) {
    // Under v1 the pools are unread too, the build's own checkout read again; under v2 they are read (owner Q-C).
    if (pool.readable !== true) for (const root of pool.deny) denyRead.add(root);
    // The build's own checkout is read again inside whatever is denied around it (the pools, a flow's sealed scratch).
    if (pool.own !== null) allowRead.add(pool.own);
    // Never written but the build's own checkout: the runtime can't write back inside a write deny, so each other
    // entry on the way is denied instead (codexPool's split, as Codex takes it).
    for (const path of codexPool(pool).deny) denyWrite.add(path);
    for (const sealed of pool.sealed ?? []) {
      denyRead.add(sealed);
      if (!(pool.own !== null && (pool.own === sealed || inside(pool.own, sealed)))) denyWrite.add(sealed);
    }
  }
  const readConfig = { denyOnly: [...denyRead].sort(), allowWithinDeny: [...allowRead].sort() };
  const writes = grants.writes;
  // A sign-ins check also writes Codex's session and log folders and its own Claude transcripts (never inside a
  // write deny: under policy v1 the home configuration stays unwritten whole).
  const signInWrites = [...grants.signIns?.writes ?? [], ...(grants.signIns?.transcripts ?? []).map(folder => join(folder, "*.jsonl"))];
  // Writing anywhere: everything but the denies. The launch's own checkout and folder are named too, so a backend that
  // binds a read deny's re-allowed paths back (bubblewrap) binds those back writable.
  const allowOnly = writes === undefined ? ["/", ...(pool?.own == null ? [] : [real(pool.own)]), ...(folders?.own == null ? [] : [folders.own])]
    : [...writes.subpaths, ...writes.prefixes.map(one => `${one.path}*`), ...signInWrites, ...getDefaultWritePaths({ denyRead: readConfig.denyOnly, allowRead: readConfig.allowWithinDeny })];
  const network = grants.network;
  return {
    readConfig,
    writeConfig: { allowOnly: [...new Set(allowOnly)].sort(), denyWithinAllow: [...denyWrite].sort() },
    allowMachLookup: [...grants.machLookup ?? [], ...grants.signIns?.mach ?? []],
    network: network === undefined || network.mode === "open" ? { kind: "open" } : {
      kind: "proxy", httpPort: network.proxyPort, ...(network.brokerPorts[0] === undefined ? {} : { socksPort: network.brokerPorts[0] }),
      ...(network.token === undefined ? {} : { token: network.token }), localServices: network.loopback === "any", unixSockets: [...network.socketRoots],
    },
  };
}

/** The spawn that runs `file args` from `cwd` inside the sandbox runtime's sandbox (sandbox-runtime.ts srtSpawn), and the
 * environment it needs beside the caller's. */
export function sandboxedSpawn(file: string, args: readonly string[], fence: readonly string[], grants: FenceGrants = NO_GRANTS, cwd?: string, temp?: string): { file: string; args: string[]; env: Record<string, string> } {
  return srtSpawn(file, args, srtTermsOf(fence, grants), cwd ?? process.cwd(), temp);
}

