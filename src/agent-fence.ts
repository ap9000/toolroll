/**
 * The agent fence: what no build, plan, scout or repair agent may read or write, whatever its permission mode. Agents
 * run as the operator's own OS user, so without it an agent could read the approver's remembered login
 * (`up-login.txt`), runner and coordinator tokens, provider keys, project tool secrets, other runs' evidence, or the
 * live database — and use them to approve its own work. The fence closes that at the operating system, not in the
 * model's instructions.
 *
 * The sandbox itself is Anthropic's sandbox-runtime (sandbox-runtime.ts): every macOS Seatbelt profile and every Linux
 * bubblewrap + seccomp invocation is generated by its code, with its baseline, its mandatory write denies (shell
 * profiles, .git/hooks, .vscode, .mcp.json and the rest) and its limits. This module decides only the few static rules
 * Toolroll passes it (srtTermsOf): Toolroll's own state and database denied to read and write; the build's own
 * checkout writable; other tasks' checkouts read, never written; the project's read-deny list; under policy v1 (an
 * approval sealed before 0.9.70) the home configuration denied by name; a sign-ins check's exact files read again; the
 * run's proxy as its only way out when its network is confined.
 *
 * Codex (every platform) fences its own agent's commands with its own sandbox: a permission profile with the same
 * denies (codexFenceArgv). Claude also gets Read/Edit deny rules for its own file tools.
 *
 * A build's fence also holds its task boundary (`taskBoundary`): under v1 the home configuration and the repositories
 * beside its own; under v2 only the primary checkout write-denied.
 */
