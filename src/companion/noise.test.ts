interface VectorFile {
  schema_version: number;
  generator: string;
  protocol_name: string;
  handshakes: Array<{
    name: string;
    protocol: string;
    mode: "pair" | "session";
    workspace_id: string;
    pair_session_id: string | null;
    device_id: string | null;
    recovery_generation: string | null;
    prologue_hex: string;
    init_static_priv_hex: string;
    init_static_pub_hex: string;
    init_ephemeral_priv_hex: string;
    resp_static_priv_hex: string;
    resp_static_pub_hex: string;
    resp_ephemeral_priv_hex: string;
    psk_hex: string;
    msg1_plaintext_utf8: string;
    msg1_hex: string;
    msg2_plaintext_utf8: string;
    msg2_hex: string;
    handshake_hash_hex: string;
    confirm_code: string | null;
    psk_entropy_hex: string | null;
    derived_device_psk_hex: string | null;
    transport: Array<{
      direction: "i2r" | "r2i";
      nonce: string;
      plaintext_utf8: string;
      ciphertext_hex: string;
    }>;
  }>;
  derivations: {
    relay_machine_pub_hex: string;
    machine_id: string;
    workspace_id: string;
    account_name: string;
    passkey_user_handle_hex: string;
  };
}

const VECTORS_PATH = resolve(process.cwd(), "test/fixtures/companion-noise/vectors.json");

function loadVectors(): VectorFile {
  return JSON.parse(readFileSync(VECTORS_PATH, "utf8")) as VectorFile;
}

describe("Noise_IKpsk2_25519_ChaChaPoly_SHA256 (Revision 34 snow vectors)", () => {
  test("passes 100% byte-exact pairing and session reconnect vectors generated by Rust snow", () => {
    const vectors = loadVectors();
    expect(vectors.protocol_name).toBe("Noise_IKpsk2_25519_ChaChaPoly_SHA256");

    for (const v of vectors.handshakes) {
      const prologue = v.mode === "pair"
        ? buildPairingPrologue(v.workspace_id, v.pair_session_id!)
        : buildSessionPrologue(v.workspace_id, v.device_id!, v.recovery_generation!);
      expect(prologue.toString("hex")).toBe(v.prologue_hex);

      const initStaticPriv = Buffer.from(v.init_static_priv_hex, "hex");
      const initStaticPub = x25519PublicFromPrivate(initStaticPriv);
      expect(initStaticPub.toString("hex")).toBe(v.init_static_pub_hex);

      const respStaticPriv = Buffer.from(v.resp_static_priv_hex, "hex");
      const respStaticPub = x25519PublicFromPrivate(respStaticPriv);
      expect(respStaticPub.toString("hex")).toBe(v.resp_static_pub_hex);

      const initEphemeralPriv = Buffer.from(v.init_ephemeral_priv_hex, "hex");
      const respEphemeralPriv = Buffer.from(v.resp_ephemeral_priv_hex, "hex");
      const psk = Buffer.from(v.psk_hex, "hex");

      const initiator = new NoiseIKpsk2Initiator({
        localStatic: { privateKey: initStaticPriv, publicKey: initStaticPub },
        remoteStaticPublicKey: respStaticPub,
        psk,
        prologue,
        ephemeralForTest: {
          privateKey: initEphemeralPriv,
          publicKey: x25519PublicFromPrivate(initEphemeralPriv),
        },
      });

      const responder = new NoiseIKpsk2Responder({
        localStatic: { privateKey: respStaticPriv, publicKey: respStaticPub },
        psk,
        prologue,
        ephemeralForTest: {
          privateKey: respEphemeralPriv,
          publicKey: x25519PublicFromPrivate(respEphemeralPriv),
        },
      });

      const msg1 = initiator.writeMessage1(Buffer.from(v.msg1_plaintext_utf8, "utf8"));
      expect(msg1.toString("hex")).toBe(v.msg1_hex);

      const r1 = responder.readMessage1(msg1);
      expect(r1.payload.toString("utf8")).toBe(v.msg1_plaintext_utf8);
      expect(r1.remoteStaticPublicKey.toString("hex")).toBe(v.init_static_pub_hex);

      const { message: msg2, session: respSession } = responder.writeMessage2(Buffer.from(v.msg2_plaintext_utf8, "utf8"));
      expect(msg2.toString("hex")).toBe(v.msg2_hex);

      const { payload: p2, session: initSession } = initiator.readMessage2(msg2);
      expect(p2.toString("utf8")).toBe(v.msg2_plaintext_utf8);
      expect(initSession.handshakeHash.toString("hex")).toBe(v.handshake_hash_hex);
      expect(respSession.handshakeHash.toString("hex")).toBe(v.handshake_hash_hex);

      if (v.confirm_code !== null) {
        expect(deriveConfirmationCode(initSession.handshakeHash)).toBe(v.confirm_code);
        expect(deriveConfirmationCode(respSession.handshakeHash)).toBe(v.confirm_code);
      }

      if (v.psk_entropy_hex !== null && v.derived_device_psk_hex !== null) {
        const derived = deriveDevicePsk(
          Buffer.from(v.psk_entropy_hex, "hex"),
          initSession.handshakeHash,
          v.workspace_id,
          "dev_11223344",
        );
        expect(derived.toString("hex")).toBe(v.derived_device_psk_hex);
      }

      for (const tm of v.transport) {
        const nonce = BigInt(tm.nonce);
        const pt = Buffer.from(tm.plaintext_utf8, "utf8");
        const expectedCt = Buffer.from(tm.ciphertext_hex, "hex");
        if (tm.direction === "i2r") {
          const ct = initSession.sendCipher.encryptExplicitNonce(nonce, Buffer.alloc(0), pt);
          expect(ct.toString("hex")).toBe(tm.ciphertext_hex);
          const dec = respSession.recvCipher.decryptExplicitNonce(nonce, Buffer.alloc(0), expectedCt);
          expect(dec.toString("utf8")).toBe(tm.plaintext_utf8);
        } else {
          const ct = respSession.sendCipher.encryptExplicitNonce(nonce, Buffer.alloc(0), pt);
          expect(ct.toString("hex")).toBe(tm.ciphertext_hex);
          const dec = initSession.recvCipher.decryptExplicitNonce(nonce, Buffer.alloc(0), expectedCt);
          expect(dec.toString("utf8")).toBe(tm.plaintext_utf8);
        }
      }
    }
  });

  test("matches deterministic machineId and passkey userHandle vectors", () => {
    const { derivations } = loadVectors();
    expect(deriveMachineId(Buffer.from(derivations.relay_machine_pub_hex, "hex"))).toBe(derivations.machine_id);
    expect(derivePasskeyUserHandle(derivations.workspace_id, derivations.account_name).toString("hex"))
      .toBe(derivations.passkey_user_handle_hex);
  });

  test("rejects recoveryGeneration prologue mismatch, wrong PSK, and tampered ciphertext", () => {
    const initStatic = generateX25519KeyPair();
    const respStatic = generateX25519KeyPair();
    const psk = Buffer.alloc(32, 0xaa);

    // 1. Prologue mismatch (recoveryGeneration mismatch) fails msg 1 decryption immediately
    const genA = "a".repeat(32);
    const genB = "b".repeat(32);
    const i1 = new NoiseIKpsk2Initiator({
      localStatic: initStatic,
      remoteStaticPublicKey: respStatic.publicKey,
      psk,
      prologue: buildSessionPrologue("ws_1", "dev_1", genA),
    });
    const r1 = new NoiseIKpsk2Responder({
      localStatic: respStatic,
      psk,
      prologue: buildSessionPrologue("ws_1", "dev_1", genB),
    });
    const m1 = i1.writeMessage1(Buffer.from("hi"));
    expect(() => r1.readMessage1(m1)).toThrow();

    // 2. Wrong PSK fails msg 2 decryption
    const prologue = buildSessionPrologue("ws_1", "dev_1", genA);
    const i2 = new NoiseIKpsk2Initiator({ localStatic: initStatic, remoteStaticPublicKey: respStatic.publicKey, psk, prologue });
    const r2 = new NoiseIKpsk2Responder({ localStatic: respStatic, psk: Buffer.alloc(32, 0xbb), prologue });
    const msg1 = i2.writeMessage1(Buffer.from("hi"));
    r2.readMessage1(msg1);
    const { message: msg2 } = r2.writeMessage2(Buffer.from("ok"));
    expect(() => i2.readMessage2(msg2)).toThrow();

    // 3. Tampered transport tag fails and closes session
    const i3 = new NoiseIKpsk2Initiator({ localStatic: initStatic, remoteStaticPublicKey: respStatic.publicKey, psk, prologue });
    const r3 = new NoiseIKpsk2Responder({ localStatic: respStatic, psk, prologue });
    r3.readMessage1(i3.writeMessage1(Buffer.from("hi")));
    const { message: okMsg2, session: rs } = r3.writeMessage2(Buffer.from("ok"));
    const { session: is } = i3.readMessage2(okMsg2);
    const ct = is.encrypt(Buffer.from("hello"));
    ct[ct.length - 1] = ct[ct.length - 1]! ^ 0xff;
    expect(() => rs.decrypt(ct)).toThrow();
    expect(rs.isExpired()).toBe(true);
  });

  test("rejects low-order X25519 keys, reserved nonce 2^64-1, 65,535 B ceiling, and 2^20 / 24h rekey limits", () => {
    expect(() => encodeNoiseNonce(RESERVED_MAX_NONCE)).toThrow();
    expect(() => encodeNoiseNonce(-1n)).toThrow();
    const high = encodeNoiseNonce((1n << 32n) + 7n);
    expect(high.toString("hex")).toBe("000000000700000001000000");

    const initStatic = generateX25519KeyPair();
    const respStatic = generateX25519KeyPair();
    const psk = Buffer.alloc(32, 0x12);
    const prologue = buildSessionPrologue("ws_1", "dev_1", "0".repeat(32));

    // Low-order all-zero public key refused
    const badInit = new NoiseIKpsk2Initiator({
      localStatic: initStatic,
      remoteStaticPublicKey: Buffer.alloc(32, 0x00),
      psk,
      prologue,
    });
    expect(() => badInit.writeMessage1(Buffer.from("hi"))).toThrow(/all zeros|low-order|failed during derivation/i);

    const i = new NoiseIKpsk2Initiator({ localStatic: initStatic, remoteStaticPublicKey: respStatic.publicKey, psk, prologue });
    const r = new NoiseIKpsk2Responder({ localStatic: respStatic, psk, prologue });
    r.readMessage1(i.writeMessage1(Buffer.from("hi")));
    const { message: msg2, session: rs } = r.writeMessage2(Buffer.from("ok"), 1_000);
    const { session: is } = i.readMessage2(msg2, 1_000);

    // Oversized Noise transport plaintext (> 65,519 bytes) refused
    expect(() => is.encrypt(Buffer.alloc(MAX_NOISE_PLAINTEXT_BYTES + 1), 1_000)).toThrow();
    expect(() => rs.decrypt(Buffer.alloc(MAX_NOISE_MESSAGE_BYTES + 1), 1_000)).toThrow();

    // 2^20 message rekey cap enforced
    is.sendCipher.setNonceForTest(MAX_SESSION_MESSAGES);
    expect(is.isExpired(1_000)).toBe(true);
    expect(() => is.encrypt(Buffer.from("too-many"), 1_000)).toThrow(/re-handshake/i);

    // 24-hour age cap enforced on a fresh live session
    const i2 = new NoiseIKpsk2Initiator({ localStatic: initStatic, remoteStaticPublicKey: respStatic.publicKey, psk, prologue });
    const r2 = new NoiseIKpsk2Responder({ localStatic: respStatic, psk, prologue });
    r2.readMessage1(i2.writeMessage1(Buffer.from("hi")));
    const { session: rs2 } = r2.writeMessage2(Buffer.from("ok"), 1_000);
    expect(rs2.isExpired(1_000 + MAX_SESSION_AGE_MS)).toBe(true);
    expect(() => rs2.encrypt(Buffer.from("too-old"), 1_000 + MAX_SESSION_AGE_MS)).toThrow(/24h/i);
  });
});

describe("Bounded RPC-over-Noise Framing & Flow Control", () => {
  test("round-trips binary frames and splits/reassembles 256 KiB requests within 5 chunks and 65,519 B Noise cap", () => {
    const bigReq = Buffer.alloc(MAX_LOGICAL_REQUEST_BYTES, 0x42);
    const frames = splitRequestFrames(1, bigReq);
    expect(frames.length).toBe(6); // 5 REQ_CHUNK + 1 END
    expect(frames.slice(0, 5).every(f => f.type === FrameType.REQ_CHUNK)).toBe(true);
    expect(frames[5]!.type).toBe(FrameType.END);

    const guard = new CompanionStreamGuard();
    let assembled: Buffer | undefined;
    for (const f of frames) {
      const encoded = encodeFrame(f);
      expect(encoded.length).toBeLessThanOrEqual(MAX_NOISE_PLAINTEXT_BYTES);
      const decoded = decodeFrame(encoded);
      const res = guard.ingestRequestFrame(decoded, 1_000);
      expect(res.ok).toBe(true);
      if (res.ok && res.completePayload) assembled = res.completePayload;
    }
    expect(assembled).toEqual(bigReq);
    expect(guard.bufferedBytes).toBe(0);

    // Requests > 256 KiB rejected
    expect(() => splitRequestFrames(3, Buffer.alloc(MAX_LOGICAL_REQUEST_BYTES + 1))).toThrow();
  });

  test("enforces monotonic odd streamId non-reuse, concurrency caps, assembly deadline, and memory caps", () => {
    const budget = new GlobalBufferBudget(100_000);
    const guard = new CompanionStreamGuard(budget);

    // Even or zero streamId refused
    expect(guard.ingestRequestFrame({ type: FrameType.REQ, streamId: 0, seq: 0, payload: Buffer.alloc(1) })).toMatchObject({ ok: false, code: "protocol_error", closeSession: true });
    expect(guard.ingestRequestFrame({ type: FrameType.REQ, streamId: 2, seq: 0, payload: Buffer.alloc(1) })).toMatchObject({ ok: false, code: "protocol_error", closeSession: true });

    // Open MAX_CONCURRENT_STREAMS (8) odd streams
    for (let i = 0; i < MAX_CONCURRENT_STREAMS; i++) {
      const id = i * 2 + 1;
      expect(guard.ingestRequestFrame({ type: FrameType.REQ, streamId: id, seq: 0, payload: Buffer.from("{}") }).ok).toBe(true);
    }
    // 9th concurrent stream refused
    expect(guard.ingestRequestFrame({ type: FrameType.REQ, streamId: 17, seq: 0, payload: Buffer.from("{}") })).toMatchObject({ ok: false, code: "too_many_streams" });

    // Reusing streamId 1 even after closing it is refused
    guard.closeStream(1);
    expect(guard.ingestRequestFrame({ type: FrameType.REQ, streamId: 1, seq: 0, payload: Buffer.from("{}") })).toMatchObject({ ok: false, code: "protocol_error", closeSession: true });

    // Assembly 5s deadline enforced
    guard.closeStream(3);
    expect(guard.ingestRequestFrame({ type: FrameType.REQ_CHUNK, streamId: 19, seq: 0, payload: Buffer.alloc(10_000) }, 1_000).ok).toBe(true);
    expect(guard.ingestRequestFrame({ type: FrameType.END, streamId: 19, seq: 1, payload: Buffer.alloc(0) }, 1_000 + REQUEST_ASSEMBLY_DEADLINE_MS + 1)).toMatchObject({ ok: false, code: "deadline_exceeded" });

    // Global memory budget enforced (100 KB budget, 2 x 60 KB chunks exceeds it)
    expect(guard.ingestRequestFrame({ type: FrameType.REQ_CHUNK, streamId: 21, seq: 0, payload: Buffer.alloc(MAX_FRAME_PAYLOAD_BYTES) }, 2_000).ok).toBe(true);
    expect(guard.ingestRequestFrame({ type: FrameType.REQ_CHUNK, streamId: 21, seq: 1, payload: Buffer.alloc(MAX_FRAME_PAYLOAD_BYTES) }, 2_000)).toMatchObject({ ok: false, code: "memory_limit" });
    expect(budget.used).toBe(0);
  });

  test("unary responses wait for CREDIT without dropping chunks and enforce 1 MiB cap + 30s deadline", () => {
    const oneMiB = Buffer.alloc(MAX_LOGICAL_UNARY_RESPONSE_BYTES, 0x7a);
    expect(() => splitUnaryResponseFrames(1, Buffer.alloc(MAX_LOGICAL_UNARY_RESPONSE_BYTES + 1))).toThrow();

    const pacer = new UnaryResponsePacer(1, oneMiB, 10_000);
    // Initial credit = 16 chunks, 1 MiB = 18 chunks + 1 END
    const first = pacer.pullAvailable(10_000);
    expect(first.ok).toBe(true);
    if (!first.ok) throw new Error("unreachable");
    expect(first.frames.length).toBe(INITIAL_STREAM_CREDIT);
    expect(pacer.done).toBe(false);

    // No credit -> yields 0 frames (does NOT drop chunks!)
    const paused = pacer.pullAvailable(15_000);
    expect(paused).toEqual({ ok: true, frames: [] });

    // Grant credit -> yields remaining 2 chunks + END, byte-exact reassembly
    const grant = decodeCreditPayload(encodeCreditPayload(4));
    pacer.grantCredit(grant);
    const rest = pacer.pullAvailable(16_000);
    expect(rest.ok).toBe(true);
    if (!rest.ok) throw new Error("unreachable");
    expect(pacer.done).toBe(true);
    const allChunks = [...first.frames, ...rest.frames].filter(f => f.type === FrameType.CHUNK).map(f => f.payload);
    expect(Buffer.concat(allChunks)).toEqual(oneMiB);

    // Stalled unary response past 30s deadline fails cleanly
    const stalled = new UnaryResponsePacer(3, oneMiB, 10_000);
    stalled.pullAvailable(10_000);
    expect(stalled.pullAvailable(10_000 + UNARY_RESPONSE_DEADLINE_MS + 1)).toEqual({ ok: false, code: "deadline_exceeded" });
  });

  test("live watch buffer caps at 32 records and emits explicit { k: 'cut' } marker when stalled", () => {
    const watch = new LiveWatchBuffer();
    watch.credit = 0;
    for (let i = 0; i < MAX_LIVE_WATCH_RECORDS + 5; i++) {
      watch.push(Buffer.from(JSON.stringify({ k: "line", i }), "utf8"));
    }
    expect(watch.length).toBe(MAX_LIVE_WATCH_RECORDS);
    watch.grantCredit(3);
    const drained = watch.drainAvailable();
    expect(drained.length).toBe(3);
    expect(JSON.parse(drained[0]!.toString("utf8"))).toEqual({ k: "cut", dropped: 5 });
    expect(JSON.parse(drained[1]!.toString("utf8"))).toEqual({ k: "line", i: 5 });
  });
});
